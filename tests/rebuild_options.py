#!/usr/bin/env python3
"""rebuild.sh asset options: validation and dry run only (no build, no write). Run from anywhere."""
import os, subprocess, sys, tempfile
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
fails = 0
def run(*args, env=None):
    p = subprocess.run(["bash", os.path.join(root, "rebuild.sh"), *args], capture_output=True, text=True, env=env)
    return p.returncode, p.stdout + p.stderr
def need(cond, msg):
    global fails
    if not cond: print("FAIL", msg); fails += 1
with tempfile.TemporaryDirectory() as d:
    rc, out = run("--help"); need(rc == 0 and "--trees" in out and "--dry-run" in out, "help lists the asset options")
    rc, out = run("--trees", "crossed", "--dry-run", env={**os.environ, "CMR2_DATA": ""}); need(rc == 2 and "--data" in out, "asset option without data stops")
    rc, out = run("--data", d + "/nope", "--trees", "crossed", "--dry-run"); need(rc == 2 and "not found" in out, "missing data folder is reported")
    rc, out = run("--data", d, "--trees", "crossed", "--dry-run"); need(rc == 2 and "frahit.bfl" in out and "found 0" in out, "missing archives are reported, not skipped")
    rc, out = run("--data", d, "--textures", "france1", "--dry-run"); need(rc == 2 and "frahit.bfl" in out, "textures need frahit.bfl")
    rc, out = run("--data", d, "--roads", "curved", "--dry-run"); need(rc == 2 and "fra01hi.bfl" in out, "roads need fra01hi.bfl")
    open(d + "/frahit.bfl", "w").close()
    rc, out = run("--data", d, "--textures", "france1", "--dry-run"); need(rc == 0 and "--prepare-only" in out and not os.path.exists(d + "/enhancements"), "texture dry run writes nothing")
    os.remove(d + "/frahit.bfl")
    for b in ("frahit", "fralot", "finhit", "finlot"): open(f"{d}/{b}.bfl", "w").close()
    rc, out = run("--data", d, "--trees", "crossed", "--spectators", "animated", "--dry-run")
    need(rc == 0 and "--trees crossed --spectators animated --prepare-only" in out and "Dry run" in out, "full dry run prints the plan")
    need(len(os.listdir(d)) == 4, "dry run leaves the data folder untouched")
    rc, out = run("--trees", "bogus"); need(rc == 2 and "crossed or shell" in out, "bad value rejected")
    rc, out = run("--bogus"); need(rc == 2 and "unknown option" in out, "unknown option rejected")
    rc, out = run("--install-enhancement-deps"); need(rc == 2, "deps flag alone rejected")
    rc, out = run("--assets-only"); need(rc == 2, "assets-only alone rejected")
    rc, out = run("--data", d, "--run", "--dry-run", "--test-preset", "atmosphere")
    need(rc == 0 and "--test-preset atmosphere" in out and "--prepare-only" not in out, "test-preset is a launch-only passthrough, no preparation")
    rc, out = run("--test-preset"); need(rc == 2, "test-preset needs a value")
    rc, out = run("--data", d, "--run", "--dry-run", "--test-preset", "atmosphere", "--fog-clear", "60")
    need(rc == 0 and "--test-preset atmosphere --fog-clear 60" in out and "--prepare-only" not in out, "fog-clear is a launch-only passthrough")
    rc, out = run("--run", "--dry-run", "--fog-clear=60", "--fog-cull=1", env={**os.environ, "CMR2_DATA": "", "OPENCMR2_DATA": ""})
    need(rc == 0 and "--fog-clear 60 --fog-cull 1" in out, "equals form normalizes to space form; tuning flags need no --data")
    rc, out = run("--data", d, "--all-mods", "--mods-dir", d, "--run", "--dry-run", "--test-preset", "atmosphere", "--fog-clear", "60")
    need(rc == 0 and "--test-preset overdo,atmosphere" in out and "--fog-clear 60" in out, "tuning flags combine with --all-mods")
    rc, out = run("--data", d, "--run", "--dry-run", "--fog-spatial", "1", "--fog-evolve=-40")
    need(rc == 0 and "--fog-spatial 1 --fog-evolve -40" in out, "fog spatial/evolve passthrough, equals normalizes")
    rc, out = run("--data", d, "--run", "--dry-run", "--fog-lights", "150")
    need(rc == 0 and "--fog-lights 150" in out, "fog lights passthrough")
    rc, out = run("--data", d, "--run", "--dry-run", "--fog-lights=0")
    need(rc == 0 and "--fog-lights 0" in out, "fog lights passthrough, equals normalizes")
    rc, out = run("--data", d, "--run", "--dry-run", "--snow-glint", "150")
    need(rc == 0 and "--snow-glint 150" in out, "snow glint passthrough")
    rc, out = run("--data", d, "--run", "--dry-run", "--snow-glint=0")
    need(rc == 0 and "--snow-glint 0" in out, "snow glint passthrough, equals normalizes")
    rc, out = run("--data", d, "--run", "--dry-run", "--snow-material", "80")
    need(rc == 0 and "--snow-material 80" in out, "snow material passthrough")
    rc, out = run("--data", d, "--run", "--dry-run", "--snow-material=0")
    need(rc == 0 and "--snow-material 0" in out, "snow material passthrough, equals normalizes")
    rc, out = run("--fog-spatial", "2"); need(rc == 2 and "0 or 1" in out, "fog-spatial validates its value")
    rc, out = run("--fog-clear"); need(rc == 2, "fog-clear needs a value")
    rc, out = run("--fog-cull", "2"); need(rc == 2 and "0 or 1" in out, "fog-cull validates its value")
print("FAILED" if fails else "rebuild options ok")
sys.exit(1 if fails else 0)
